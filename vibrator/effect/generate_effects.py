# Generates standard_effect.h and primitive_effect.h from the stock OPLUS vibrator
# library (odm/etc/vibrator), so the QTI vibrator HAL plays the same waveforms as the
# unified OPLUS HAL (hardware/oplus aidl/vibrator/oplus) with the 816 motor tuning.
#
# Usage: generate_effects.py <stock odm/etc/vibrator dir>

import json
import os
import sys

MOTOR = '816'

# AOSP Effect id -> stock effect id.
EFFECTS = [
    (0, 0, 'CLICK'),
    (1, 1, 'DOUBLE_CLICK'),
    (2, 2, 'TICK'),
    (3, 3, 'THUD'),
    (4, 4, 'POP'),
    (5, 5, 'HEAVY_CLICK'),
    (21, 7, 'TEXTURE_TICK'),
]

# AOSP CompositePrimitive id -> stock effect id, None for silence. LOW_TICK is 305 (lighter slider ticks), unlike MotorTuning.cpp.
PRIMITIVES = [
    (0, None, 'NOOP'),
    (1, 0, 'CLICK'),
    (2, 3, 'THUD'),
    (3, 364, 'SPIN'),
    (4, 302, 'QUICK_RISE'),
    (5, 362, 'SLOW_RISE'),
    (6, 310, 'QUICK_FALL'),
    (7, 303, 'LIGHT_TICK'),
    (8, 305, 'LOW_TICK'),
]

HEADER = '''/*
 * SPDX-FileCopyrightText: The LineageOS Project
 * SPDX-License-Identifier: Apache-2.0
 */

/* Generated by generate_effects.py from the stock vibrator library, motor {motor}. */

'''


def load_stock(vibrator_dir):
    with open(os.path.join(vibrator_dir, 'vibrator_effect.json')) as f:
        table = json.load(f)[MOTOR]['def_style']
    stock = {}
    for entry in table:
        path = os.path.join(vibrator_dir, os.path.relpath(entry['effect_file'],
                                                          '/odm/etc/vibrator'))
        with open(path, 'rb') as f:
            data = f.read()
        stock[entry['effect_id']] = ([b - 256 if b > 127 else b for b in data],
                                     entry['play_rate_hz'])
    return stock


def format_array(name, samples):
    lines = [f'static const int8_t {name}[] = {{']
    for i in range(0, len(samples), 16):
        lines.append('    ' + ''.join(f'{s:5d},' for s in samples[i:i + 16]))
    lines.append('};')
    return '\n'.join(lines) + '\n\n'


def write_header(path, prefix, table_name, mapping, stock):
    out = HEADER.format(motor=MOTOR)
    entries = []
    for aosp_id, stock_id, label in mapping:
        if stock_id is None:
            samples, rate = [0] * 9, 24000
            source = 'silence'
        else:
            samples, rate = stock[stock_id]
            source = f'stock effect {stock_id}'
        name = f'{prefix}_{aosp_id}'
        out += f'/* {label}: {source} */\n' + format_array(name, samples)
        entries.append(f'''    {{
        /* {label} */
        .effect_id = {aosp_id},
        .length = ARRAY_SIZE({name}),
        .play_rate_hz = {rate},
        .data = {name},
    }},
''')
    out += f'static const struct effect_stream {table_name}[] = {{\n'
    out += '\n'.join(entries)
    out += '};\n'
    with open(path, 'w') as f:
        f.write(out)


def main():
    if len(sys.argv) != 2:
        sys.exit(f'usage: {sys.argv[0]} <stock odm/etc/vibrator dir>')
    stock = load_stock(sys.argv[1])
    here = os.path.dirname(os.path.abspath(__file__))
    write_header(os.path.join(here, 'standard_effect.h'), 'effect', 'effects', EFFECTS, stock)
    write_header(os.path.join(here, 'primitive_effect.h'), 'primitive', 'primitives',
                 PRIMITIVES, stock)


if __name__ == '__main__':
    main()
